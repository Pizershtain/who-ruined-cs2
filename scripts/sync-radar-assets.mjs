import { createHash } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Pin the images and overview metadata together. Updates require an explicit revision.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const settingsPath = path.join(root, 'scripts/radar-catalog.json');
const settings = JSON.parse(await readFile(settingsPath, 'utf8'));
const defaultRevision = settings.revision;
const args = process.argv.slice(2);
if (args.length && !(args.length === 1 && args[0] === '--check') && !(args.length === 2 && ['--revision', '--activate'].includes(args[0]))) throw new Error('Use --check, --revision <commit>, or --activate <commit>');
const revision = args[1] ?? defaultRevision;
if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error('A full source commit is required');
const repository = 'https://raw.githubusercontent.com/MurkyYT/cs2-map-icons/';
const sourceRoot = `${repository}${revision}/`;
const output = path.join(root, 'apps/web/public/maps', revision);

if (args[0] === '--check') {
  const response = await fetch('https://api.github.com/repos/MurkyYT/cs2-map-icons/commits/main', { headers: { 'User-Agent': 'who-ruined-cs2-map-assets' }, signal: AbortSignal.timeout(15_000), redirect: 'error' });
  if (!response.ok) throw new Error(`Update check failed: ${response.status}`);
  const latest = (await response.json()).sha;
  if (!/^[a-f0-9]{40}$/.test(latest)) throw new Error('Invalid source revision');
  console.log(JSON.stringify({ active: defaultRevision, latest, updateAvailable: latest !== defaultRevision }, null, 2));
  process.exit(0);
}
if (args[0] === '--activate') {
  const { replayRadarCalibrationSchema } = await import('../packages/contracts/dist/index.js');
  const manifest = JSON.parse(await readFile(path.join(output, 'manifest.json'), 'utf8'));
  if (manifest.revision !== revision || !Object.keys(manifest.maps).length) throw new Error('Invalid staged manifest');
  const calibrations = {};
  for (const [map, data] of Object.entries(manifest.maps)) {
    const calibration = replayRadarCalibrationSchema.parse(data.calibration);
    if (calibration.map !== map || data.images.length !== calibration.layers.length) throw new Error(`Invalid map binding: ${map}`);
    for (const layer of calibration.layers) {
      const expected = data.images.find(image => image.id === layer.id && image.imageUrl === layer.imageUrl);
      const prefix = `/maps/${revision}/`;
      if (!expected || !layer.imageUrl.startsWith(prefix)) throw new Error(`Invalid layer binding: ${map}`);
      const filename = layer.imageUrl.slice(prefix.length);
      const bytes = await readFile(path.join(output, filename));
      const dimensions = imageSize(bytes);
      if (createHash('sha256').update(bytes).digest('hex') !== expected.sha256 || bytes.length !== expected.bytes || dimensions.width !== expected.width || dimensions.height !== expected.height) throw new Error(`Asset verification failed: ${filename}`);
    }
    calibrations[map] = calibration;
  }
  const generated = `// Generated by npm.cmd run maps:activate. Do not edit.\n// Source: https://github.com/MurkyYT/cs2-map-icons/tree/${revision}\n// Radar images and overview data are property of Valve Corporation.\nimport type { ReplayRadarCalibration } from '@who-ruined/contracts';\n\nexport const replayMapCatalog: Readonly<Record<string, ReplayRadarCalibration>> = ${JSON.stringify(calibrations, null, 2)};\n`;
  const destination = path.join(root, 'apps/api/src/application/replay-map-catalog.generated.ts');
  await writeFile(destination + '.tmp', generated);
  await rename(destination + '.tmp', destination);
  await writeFile(settingsPath, JSON.stringify({ revision }, null, 2) + '\n');
  console.log(`Activated ${Object.keys(calibrations).length} maps from ${revision}. Rebuild API and web together. Older asset directories are retained.`);
  process.exit(0);
}
await mkdir(output, { recursive: true });

async function download(relative, maxBytes) {
  const response = await fetch(sourceRoot + relative, { signal: AbortSignal.timeout(30_000), redirect: 'error' });
  if (!response.ok || !response.body) throw new Error(`Download failed: ${relative} (${response.status})`);
  const chunks = []; let length = 0;
  for await (const chunk of response.body) {
    length += chunk.length;
    if (length > maxBytes) { await response.body.cancel().catch(() => {}); throw new Error(`Oversized asset: ${relative}`); }
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}
function sourcePath(url, folder) {
  const prefix = `${repository}main/${folder}/`;
  if (typeof url !== 'string' || !url.startsWith(prefix)) throw new Error('Unexpected asset source');
  const name = url.slice(prefix.length);
  if (!/^[a-z0-9_]+\.(png|txt)$/.test(name)) throw new Error('Invalid asset name');
  return `${folder}/${name}`;
}
async function immutableFile(name, bytes) {
  const destination = path.join(output, name);
  const existing = await readFile(destination).catch(error => { if (error.code !== 'ENOENT') throw error; return null; });
  if (existing && !existing.equals(bytes)) throw new Error(`Pinned asset changed: ${name}`);
  if (!existing) await writeFile(destination, bytes, { flag: 'wx' });
}
function imageSize(bytes) {
  if (bytes.length < 24 || !bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10]))) throw new Error('Invalid PNG');
  const width = bytes.readUInt32BE(16), height = bytes.readUInt32BE(20);
  if (width !== height || ![1024, 2048].includes(width)) throw new Error(`Unsupported radar dimensions: ${width}x${height}`);
  return { width, height };
}

const sourceCatalog = JSON.parse((await download('data/available.json', 2_000_000)).toString('utf8'));
const maps = {}, skipped = [];
for (const [map, entry] of Object.entries(sourceCatalog.maps).sort(([a], [b]) => a.localeCompare(b))) {
  // Segmented training maps need their own per-segment transforms, not a guessed global radar.
  if (!/^(de|cs|ar)_[a-z0-9_]+$/.test(map) || !entry.radar_info || !entry.radar_paths?.length) { skipped.push(map); continue; }
  const info = entry.radar_info;
  if (![info.pos_x, info.pos_y, info.scale].every(Number.isFinite) || info.scale <= 0) throw new Error(`Invalid transform: ${map}`);
  const overviewPath = sourcePath(info.path, 'data/radar_info');
  const overview = await download(overviewPath, 100_000);
  const text = overview.toString('utf8');
  for (const key of ['pos_x', 'pos_y', 'scale']) {
    const value = text.match(new RegExp(`"${key}"\\s+"([^\"]+)"`))?.[1];
    if (Number(value) !== info[key]) throw new Error(`Overview disagrees with catalogue: ${map}.${key}`);
  }
  const paths = entry.radar_paths.map(url => sourcePath(url, 'images/radars'));
  const sections = Object.entries(info.verticalsections ?? { default: null });
  const images = [];
  for (const [level, range] of sections) {
    if (!/^[a-z0-9_]+$/.test(level)) throw new Error(`Invalid layer: ${map}`);
    const stem = level === 'default' ? map : `${map}_${level}`;
    const imagePath = ['psd', 'tga', ''].map(ext => `images/radars/${stem}_radar${ext ? '_' + ext : ''}.png`).find(candidate => paths.includes(candidate));
    if (!imagePath) throw new Error(`No unambiguous image for ${map}/${level}`);
    if (range && (!Number.isFinite(range.AltitudeMin) || !Number.isFinite(range.AltitudeMax) || range.AltitudeMin >= range.AltitudeMax)) throw new Error(`Invalid altitude range: ${map}/${level}`);
    const bytes = await download(imagePath, 10_000_000);
    const dimensions = imageSize(bytes);
    const filename = `${stem}.png`;
    await immutableFile(filename, bytes);
    images.push({ id: level, imageUrl: `/maps/${revision}/${filename}`, minZ: range?.AltitudeMin ?? null, maxZ: range?.AltitudeMax ?? null,
      source: sourceRoot + imagePath, sha256: createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length, ...dimensions });
  }
  if (!images.some(image => image.id === 'default')) throw new Error(`Missing default layer: ${map}`);
  await immutableFile(`${map}.txt`, overview);
  const calibration = {
    id: `${map}-radar@${revision.slice(0, 12)}`, map,
    // Valve overview scale is world units per pixel on a 1024-unit radar, including 2048px exports.
    imageWidth: 1024, imageHeight: 1024, posX: info.pos_x, posY: info.pos_y, scale: info.scale, rotate: info.rotate ?? 0,
    source: 'VALVE_OVERVIEW_METADATA', sourceVersion: `CS2 radar catalogue ${revision}`,
    imageUrl: images.find(image => image.id === 'default').imageUrl,
    layers: images.map(({ id, imageUrl, minZ, maxZ }) => ({ id, imageUrl, minZ, maxZ })),
  };
  maps[map] = { calibration, overview: sourceRoot + overviewPath, images };
  console.log(`${map}: ${images.length} layer(s)`);
}
const manifest = { revision, source: 'https://github.com/MurkyYT/cs2-map-icons', attribution: 'Radar images and overview data are property of Valve Corporation.', maps, skipped };
await immutableFile('manifest.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'));
console.log(`Staged ${Object.keys(maps).length} maps; active catalogue unchanged. No usable overview/image pair: ${skipped.join(', ')}`);
console.log(`After review: npm.cmd run maps:activate -- ${revision}`);
